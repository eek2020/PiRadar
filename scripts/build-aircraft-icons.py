"""Bundle the aircraft icon SVGs into frontend/aircraft-shapes.js.

    python3 scripts/build-aircraft-icons.py

Reads every SVG in assets/aircraft-icons/*/ and keeps only the geometry
(paths, groups and their transforms). Colours, strokes, editor metadata and
definitions are dropped because the map colours icons itself. Icon names are
the file names; a name may appear in only one source folder.
"""

from __future__ import annotations

import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "assets" / "aircraft-icons"
OUTPUT = ROOT / "frontend" / "aircraft-shapes.js"

SVG = "http://www.w3.org/2000/svg"
SHAPE_TAGS = {"path", "g", "circle", "ellipse", "rect", "polygon", "polyline"}
GEOMETRY = {"d", "transform", "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "points", "fill-rule"}


def compact(value: str) -> str:
    return " ".join(value.split())


def geometry(element: ET.Element) -> str:
    """Serialise an element's shape children, keeping geometry only."""
    parts = []
    for child in element:
        namespace, _, tag = child.tag.rpartition("}")
        if namespace.lstrip("{") != SVG or tag not in SHAPE_TAGS:
            continue
        attributes = "".join(
            f' {name}="{compact(value)}"'
            for name, value in child.attrib.items()
            if name in GEOMETRY
        )
        inner = geometry(child)
        if tag == "g" and not inner:
            continue
        parts.append(f"<{tag}{attributes}>{inner}</{tag}>" if inner else f"<{tag}{attributes}/>")
    return "".join(parts)


def view_box(root: ET.Element, path: Path) -> str:
    raw = root.get("viewBox")
    if not raw:
        raise ValueError(f"{path} has no viewBox")
    return " ".join(f"{float(number):g}" for number in raw.replace(",", " ").split())


def main() -> None:
    shapes: dict[str, dict[str, str]] = {}
    origins: dict[str, str] = {}
    for path in sorted(SOURCES.glob("*/*.svg")):
        name = path.stem
        if name in shapes:
            raise SystemExit(f"icon '{name}' is in both {origins[name]} and {path.parent.name}")
        root = ET.parse(path).getroot()
        markup = geometry(root)
        if not markup:
            raise SystemExit(f"{path} contains no shapes")
        shapes[name] = {"viewBox": view_box(root, path), "markup": markup}
        origins[name] = path.parent.name

    body = json.dumps(shapes, indent=1, sort_keys=True)
    OUTPUT.write_text(
        "// Generated by scripts/build-aircraft-icons.py from assets/aircraft-icons; do not edit.\n"
        "// Includes icons by ADS-B Radar for macOS - https://adsb-radar.com - "
        "https://apps.apple.com/app/id1538149835\n"
        f"window.PiRadarShapes = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(shapes)} icons to {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
